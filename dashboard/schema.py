"""The data contract between the pipeline and the dashboard.

The dashboard loads dashboard/data.js, which sets window.TRACKER_DATA. (A script
rather than JSON so the data loads without fetch().) pipeline/export.py writes it
for real; dashboard/mock_data.py writes a placeholder. Both should produce:

  meta:
    is_mock        bool    shows the "Mock data" banner when true
    generated_at   str     ISO 8601 timestamp
    period_start   str     earliest date covered (YYYY-MM-DD, or coarser)
    period_end     str     latest date covered
    states         [{name, code}]
    categories     [{id, label}]   display order
    sectors        [str]           display order
    stages         [{id, label}]   optional; the stage ids items may carry
  items: one per record
    required  id, date, state, title, source, url, category, tags, sector
              date: "YYYY-MM-DD", "YYYY-MM", "YYYY" or "" (see date_precision)
              category: primary category id; tags: all category ids incl. the primary
    optional  date_precision ("day" | "month" | "year" | "unknown"), summary,
              image (thumbnail URL, "" if none), n_sources (int),
              also_reported_by ([str] or "; "-joined str),
              stage (an id from meta.stages, or "" when not judged)

The taxonomy, states and sectors travel in meta, so changing them needs no
dashboard code changes. validate() is the full check; js/data.js runs a lighter one.
"""
import json
import re
from pathlib import Path

DATA_PATH = Path(__file__).resolve().parent / "data.js"

_DATE = re.compile(r"^(\d{4}(-\d{2}(-\d{2})?)?)?$")
REQUIRED = {"id": str, "date": str, "state": str, "title": str, "source": str,
            "url": str, "category": str, "tags": list, "sector": str}
OPTIONAL = {"date_precision": str, "summary": str, "image": str, "n_sources": int,
            "also_reported_by": (list, str), "stage": str}
MAX_ERRORS = 10


class SchemaError(ValueError):
    pass


def validate(data: dict) -> None:
    """Raise SchemaError listing up to MAX_ERRORS problems."""
    meta, items = data.get("meta"), data.get("items")
    if not isinstance(meta, dict) or not isinstance(items, list):
        raise SchemaError("top level must have 'meta' (object) and 'items' (list)")
    errors: list[str] = []
    states = {s.get("name") for s in meta.get("states", [])}
    categories = {c.get("id") for c in meta.get("categories", [])}
    sectors = set(meta.get("sectors", []))
    stages = {s.get("id") for s in meta.get("stages", [])} | {""}
    if not (states and categories and sectors):
        errors.append("meta.states, meta.categories and meta.sectors must be non-empty")

    ids: set[str] = set()
    for i, it in enumerate(items):
        if len(errors) >= MAX_ERRORS:
            break
        where = f"items[{i}]"
        bad = [f for f, t in REQUIRED.items() if not isinstance(it.get(f), t)]
        bad += [f for f, t in OPTIONAL.items() if f in it and not isinstance(it[f], t)]
        if bad:
            errors.append(f"{where} has missing or mistyped fields {bad}")
            continue
        if it["id"] in ids:
            errors.append(f"{where}.id {it['id']!r} is duplicated")
        ids.add(it["id"])
        if not _DATE.match(it["date"]):
            errors.append(f"{where}.date {it['date']!r} is not YYYY[-MM[-DD]] or empty")
        if it["state"] not in states:
            errors.append(f"{where}.state {it['state']!r} is not in meta.states")
        if it["category"] not in it["tags"]:
            errors.append(f"{where}.tags must include the primary category")
        if unknown := set(it["tags"]) - categories:
            errors.append(f"{where}.tags has unknown ids {sorted(unknown)}")
        if it["sector"] not in sectors:
            errors.append(f"{where}.sector {it['sector']!r} is not in meta.sectors")
        if it.get("stage", "") not in stages:
            errors.append(f"{where}.stage {it['stage']!r} is not in meta.stages")
    if errors:
        raise SchemaError("; ".join(errors[:MAX_ERRORS]))


def write(data: dict, path: Path = DATA_PATH, generator: str = "dashboard/schema.py") -> Path:
    """Validate, then write data.js with one item per line (small, readable diffs)."""
    validate(data)
    meta = json.dumps(data["meta"], ensure_ascii=False)
    rows = ",\n".join(json.dumps(it, ensure_ascii=False) for it in data["items"])
    path.write_text(f"// Generated by {generator}. Do not edit.\n"
                    f'window.TRACKER_DATA = {{"meta": {meta},\n"items": [\n{rows}\n]}};\n',
                    encoding="utf-8")
    return path
