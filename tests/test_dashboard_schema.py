"""The dashboard's data contract (dashboard/schema.py).

Run:  python -m unittest tests.test_dashboard_schema
"""
import copy
import json
import tempfile
import unittest
from pathlib import Path

from dashboard import schema

VALID = {
    "meta": {
        "is_mock": True, "generated_at": "2026-11-01T00:00:00+00:00",
        "period_start": "2025-11-01", "period_end": "2026-10-31",
        "states": [{"name": "Kerala", "code": "KL"}],
        "categories": [{"id": "deployment", "label": "Deployment"},
                       {"id": "skilling", "label": "Skilling"}],
        "sectors": ["Health", "Cross-cutting"],
    },
    "items": [{
        "id": "R1", "date": "2026-03-04", "date_precision": "day", "state": "Kerala",
        "title": "Kerala pilots AI tool", "summary": "", "source": "Outlet", "url": "",
        "image": "", "category": "deployment", "tags": ["deployment", "skilling"],
        "sector": "Health", "n_sources": 2, "also_reported_by": ["Other outlet"],
    }],
}


def with_item(**changes):
    data = copy.deepcopy(VALID)
    data["items"][0].update(changes)
    return data


class ValidateTest(unittest.TestCase):
    def test_valid_data_passes(self):
        schema.validate(VALID)

    def test_partial_and_missing_dates_pass(self):
        for d in ["2026-03", "2026", ""]:
            schema.validate(with_item(date=d))

    def test_rejects_unknown_state_tag_and_sector(self):
        for bad, needle in [({"state": "Goa"}, "meta.states"),
                            ({"tags": ["deployment", "nope"]}, "unknown ids"),
                            ({"sector": "Space"}, "meta.sectors")]:
            with self.subTest(bad=bad), self.assertRaisesRegex(schema.SchemaError, needle):
                schema.validate(with_item(**bad))

    def test_primary_category_must_be_in_tags(self):
        with self.assertRaisesRegex(schema.SchemaError, "primary category"):
            schema.validate(with_item(tags=["skilling"]))

    def test_rejects_missing_fields_and_bad_dates(self):
        data = with_item()
        del data["items"][0]["title"]
        with self.assertRaisesRegex(schema.SchemaError, "title"):
            schema.validate(data)
        with self.assertRaisesRegex(schema.SchemaError, "date"):
            schema.validate(with_item(date="04/03/2026"))

    def test_rejects_duplicate_ids(self):
        data = copy.deepcopy(VALID)
        data["items"].append(copy.deepcopy(data["items"][0]))
        with self.assertRaisesRegex(schema.SchemaError, "duplicated"):
            schema.validate(data)


class WriteTest(unittest.TestCase):
    def test_round_trip(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = schema.write(VALID, Path(tmp) / "data.js")
            text = path.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("// Generated by"))
        self.assertIn("window.TRACKER_DATA = ", text)
        body = text[text.index("{"): text.rindex("}") + 1]
        self.assertEqual(json.loads(body), VALID)

    def test_stage_must_be_listed_in_meta(self):
        data = with_item(stage="decided")
        data["meta"]["stages"] = [{"id": "decided", "label": "Approved or signed"}]
        schema.validate(data)
        schema.validate(with_item(stage=""))  # not judged
        with self.assertRaises(schema.SchemaError):
            schema.validate(with_item(stage="decided"))  # no meta.stages

    def test_does_not_write_invalid_data(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "data.js"
            with self.assertRaises(schema.SchemaError):
                schema.write(with_item(state="Goa"), path)
            self.assertFalse(path.exists())


if __name__ == "__main__":
    unittest.main()
